CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at BIGINT NOT NULL,
 CONSTRAINT user_role CHECK (role IN ('ADMIN','CREATOR','PARTICIPANT'))
);
CREATE TABLE IF NOT EXISTS quizzes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(160) NOT NULL, description VARCHAR(2000) NOT NULL,
 topic VARCHAR(80) NOT NULL, difficulty VARCHAR(20) NOT NULL,
 duration_minutes INT NOT NULL, creator_id BIGINT NOT NULL REFERENCES app_users(id),
 status VARCHAR(20) NOT NULL, review_note VARCHAR(1000) DEFAULT '', created_at BIGINT NOT NULL,
 CONSTRAINT quiz_status CHECK (status IN ('DRAFT','PENDING','APPROVED','REJECTED')),
 CONSTRAINT quiz_duration CHECK (duration_minutes BETWEEN 1 AND 180)
);
CREATE TABLE IF NOT EXISTS questions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE, position INT NOT NULL,
 prompt VARCHAR(4000) NOT NULL, option_a VARCHAR(1000) NOT NULL, option_b VARCHAR(1000) NOT NULL,
 option_c VARCHAR(1000) NOT NULL, option_d VARCHAR(1000) NOT NULL,
 correct_index INT NOT NULL, explanation VARCHAR(3000) NOT NULL,
 CONSTRAINT correct_option CHECK (correct_index BETWEEN 0 AND 3)
);
CREATE TABLE IF NOT EXISTS attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 quiz_id BIGINT NOT NULL REFERENCES quizzes(id), participant_id BIGINT NOT NULL REFERENCES app_users(id),
 started_at BIGINT NOT NULL, deadline_at BIGINT NOT NULL, submitted_at BIGINT,
 score INT DEFAULT 0 NOT NULL, manual_score INT, total INT NOT NULL, pass_percent INT NOT NULL,
 grade_feedback VARCHAR(3000) DEFAULT '', reviewed_by BIGINT REFERENCES app_users(id)
);
CREATE TABLE IF NOT EXISTS answers (
 attempt_id BIGINT NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
 question_id BIGINT NOT NULL REFERENCES questions(id), selected_index INT NOT NULL,
 PRIMARY KEY (attempt_id, question_id), CONSTRAINT selected_option CHECK (selected_index BETWEEN 0 AND 3)
);
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender_id BIGINT NOT NULL REFERENCES app_users(id), recipient_id BIGINT NOT NULL REFERENCES app_users(id),
 body VARCHAR(3000) NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS reminders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id), quiz_id BIGINT NOT NULL REFERENCES quizzes(id),
 remind_at BIGINT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS system_settings (
 id INT PRIMARY KEY, site_name VARCHAR(100) NOT NULL,
 pass_percent INT NOT NULL, default_duration INT NOT NULL,
 max_attempts INT NOT NULL, maintenance BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_attempt_user ON attempts(participant_id,quiz_id);
CREATE INDEX IF NOT EXISTS idx_question_quiz ON questions(quiz_id);
CREATE INDEX IF NOT EXISTS idx_message_users ON messages(sender_id,recipient_id);
